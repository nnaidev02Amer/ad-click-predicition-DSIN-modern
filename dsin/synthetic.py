"""Synthetic DEMO data with the same file/column structure as the Taobao dataset.

DEMO DATA ONLY - NOT REAL TAOBAO RECORDS. Any metric computed from it says nothing about
the performance of DSIN on the genuine dataset.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from .config import Paths, BEHAVIOR_START_TS, SPLIT_TS

DAY = 86400


def generate_demo_raw(paths: Paths, n_users=1500, n_ads=300, n_cates=30, n_brands=60, n_samples=25000, seed=2024):
    """Write raw_sample.csv, ad_feature.csv, user_profile.csv, behavior_log.csv under paths.raw."""
    rng = np.random.default_rng(seed)
    out = paths.raw
    out.mkdir(parents=True, exist_ok=True)

    user_ids = rng.choice(np.arange(100000, 900000), n_users, replace=False)
    user = pd.DataFrame({
        'userid': user_ids,
        'cms_segid': rng.integers(0, 40, n_users),
        'cms_group_id': rng.integers(1, 14, n_users),
        'final_gender_code': rng.integers(1, 3, n_users),
        'age_level': rng.integers(1, 7, n_users),
        'pvalue_level': rng.choice([np.nan, 1, 2, 3], n_users, p=[.3, .25, .3, .15]),
        'shopping_level': rng.integers(1, 4, n_users),
        'occupation': rng.integers(0, 2, n_users),
        'new_user_class_level': rng.choice([np.nan, 1, 2, 3, 4], n_users, p=[.2, .1, .3, .3, .1])})
    # the original file has a trailing space in this header
    user = user.rename(columns={'new_user_class_level': 'new_user_class_level '})

    cate_raw = rng.choice(np.arange(1000, 9000), n_cates, replace=False)
    brand_raw = rng.choice(np.arange(10000, 90000), n_brands, replace=False)
    ad = pd.DataFrame({
        'adgroup_id': rng.choice(np.arange(200000, 900000), n_ads, replace=False),
        'cate_id': rng.choice(cate_raw, n_ads),
        'campaign_id': rng.integers(1000, 1100, n_ads),
        'customer': rng.integers(1, 120, n_ads),
        'brand': rng.choice(np.append(brand_raw, np.nan), n_ads),
        'price': np.round(rng.lognormal(4, 1, n_ads), 2)})

    # each user has 2 preferred categories; clicks are likelier when the ad category matches
    pref = {u: rng.choice(cate_raw, 2, replace=False) for u in user_ids}

    # behaviour log: bursts (sessions) of page views from BEHAVIOR_START_TS to the end of the sample window
    t_end = SPLIT_TS + 3 * DAY
    rows = []
    for u in user_ids:
        for _ in range(rng.integers(3, 12)):
            start = rng.integers(BEHAVIOR_START_TS, t_end)
            n = rng.integers(2, 9)
            ts = start + np.cumsum(rng.integers(5, 600, n))
            cates = np.where(rng.random(n) < .7, rng.choice(pref[u], n), rng.choice(cate_raw, n))
            brands = rng.choice(brand_raw, n)
            for t, c, b in zip(ts, cates, brands):
                rows.append((u, t, 'pv', c, b))
        rows.append((u, BEHAVIOR_START_TS + 5, 'cart', cate_raw[0], brand_raw[0]))  # non-pv: must be filtered
    beh = pd.DataFrame(rows, columns=['user', 'time_stamp', 'btag', 'cate', 'brand'])

    s_user = rng.choice(user_ids, n_samples)
    s_ad = rng.integers(0, n_ads, n_samples)
    s_ts = rng.integers(BEHAVIOR_START_TS + 3 * DAY, t_end, n_samples)
    match = np.array([ad['cate_id'].iloc[a] in pref[u] for u, a in zip(s_user, s_ad)])
    p = np.where(match, 0.35, 0.05)
    clk = (rng.random(n_samples) < p).astype(int)
    sample = pd.DataFrame({'user': s_user, 'time_stamp': s_ts, 'adgroup_id': ad['adgroup_id'].values[s_ad],
                           'pid': rng.choice(['430548_1007', '430539_1007'], n_samples),
                           'nonclk': 1 - clk, 'clk': clk}).sort_values('time_stamp')

    user.to_csv(out / 'user_profile.csv', index=False)
    ad.to_csv(out / 'ad_feature.csv', index=False)
    beh.to_csv(out / 'behavior_log.csv', index=False)
    sample.to_csv(out / 'raw_sample.csv', index=False)
    (out / 'README_DEMO.txt').write_text(
        'SYNTHETIC DEMO DATA generated by dsin/synthetic.py. These are NOT Taobao records.\n', encoding='utf-8')
    return {'users': n_users, 'ads': n_ads, 'samples': n_samples, 'behavior_rows': len(beh),
            'click_rate': float(clk.mean())}
